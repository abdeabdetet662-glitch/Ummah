package com.ummah.app;

public class Constitution {
    public static class Article {
        public int number;
        public String title;
        public String text;
        public Article(int n, String t, String x) { number = n; title = t; text = x; }
    }
    public static Article[] getArticles() {
        return new Article[]{
            new Article(1, "الكرامة", "لكل مواطن كرامة لا تُمس. لا يُهان، ولا يُحقر، ولا يُعامل بدون احترام."),
            new Article(2, "الحرية", "المواطن حر في فكره وتعبيره ومعتقده. لا يُحتجز إلا بحكم قضائي معلل."),
            new Article(3, "العدالة", "القضاء مستقل. كل مواطن متساوٍ أمام القانون. لا أحد فوق المحاسبة."),
            new Article(4, "المساواة", "لا تمييز بين المواطنين بسبب الجنس أو اللون أو الأصل أو اللغة أو الدين."),
            new Article(5, "التعليم", "التعليم حق لكل مواطن. المعرفة مفتوحة، مجانية، ومتاحة للجميع."),
            new Article(6, "الصحة", "الصحة حق لكل مواطن. لا يُحرم أحد من الرعاية بسبب الفقر أو الموقع."),
            new Article(7, "العمل", "العمل حق وشرف. لكل مواطن أن يختار عمله، وأن يتقاضى أجراً عادلاً."),
            new Article(8, "الخصوصية", "بيانات المواطن ملكه. لا تُراقب، ولا تُشارك، ولا تُستخدم بدون إذنه."),
            new Article(9, "الملكية", "الملكية الخاصة مصونة. لا تُنزع إلا للمصلحة العامة وبقانون وتعادل."),
            new Article(10, "التصويت", "لكل مواطن صوت واحد. القرارات تُبنى بالأغلبية. لا وصاية على الإرادة.")
        };
    }
}
